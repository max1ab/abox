import type { FastifyInstance } from "fastify";
import type { Pool } from "pg";

// Separate tables and transaction from the unmodified upstream migrations.
export async function migrateCollaboration(pool: Pool): Promise<void> {
  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    await client.query("SELECT pg_advisory_xact_lock(738249110)");
    await client.query(`CREATE TABLE IF NOT EXISTS am_board_posts (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      team TEXT NOT NULL, author TEXT NOT NULL, body TEXT NOT NULL,
      created_at TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
    );
    CREATE INDEX IF NOT EXISTS am_board_team_id ON am_board_posts(team, id);
    CREATE TABLE IF NOT EXISTS am_agent_profiles (
      team TEXT NOT NULL, agent TEXT NOT NULL, display_name TEXT NOT NULL,
      description TEXT NOT NULL,
      updated_at TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
      PRIMARY KEY(team, agent)
    );`);
    await client.query("COMMIT");
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally { client.release(); }
}

export function validLabel(value: unknown): value is string {
  return typeof value === "string" && value.length > 0 && value.trim() === value
    && Array.from(value).length <= 128 && !/\p{Cc}/u.test(value) && !value.includes("\0");
}
function object(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}
function fields<const K extends string>(value: unknown, names: K[]): value is Record<K, string> {
  return object(value) && Object.keys(value).length === names.length
    && names.every((key) => typeof value[key] === "string");
}
function positive(value: unknown, max = Number.MAX_SAFE_INTEGER): number | undefined {
  if (typeof value !== "string" || !/^[1-9][0-9]*$/.test(value)) return undefined;
  const n = Number(value);
  return Number.isSafeInteger(n) && n <= max ? n : undefined;
}
function post(row: Record<string, unknown>) {
  const id = Number(row.id);
  if (!Number.isSafeInteger(id)) throw new Error("post ID exceeds JSON integer range");
  return { ...row, id };
}

// This service retains the existing trusted-network API. Names are claims,
// not authenticated identities. Board posts never touch mail or wake channels.
export async function collaboration(app: FastifyInstance, pool: Pool): Promise<void> {
  app.setErrorHandler((error, request, reply) => {
    const candidate = error instanceof Error && "statusCode" in error ? error.statusCode : undefined;
    const status = typeof candidate === "number" && candidate >= 400 && candidate < 500 ? candidate : 500;
    if (status === 500) request.log.error({ err: error }, "collaboration request failed");
    void reply.code(status).send({ error: status === 500 ? "storage error" : "invalid request" });
  });
  app.get("/v1/agent-mail/health", async () => {
    await pool.query("SELECT 1 FROM am_board_posts LIMIT 0");
    await pool.query("SELECT 1 FROM am_agent_profiles LIMIT 0");
    return { service: "agent-mail", status: "ok" };
  });
  app.post("/v1/board/posts", { bodyLimit: 1024 * 1024 }, async (request, reply) => {
    const b = request.body;
    if (!fields(b, ["team", "author", "body"]) || !validLabel(b.team) || !validLabel(b.author)
      || !b.body.trim() || b.body.includes("\0") || Buffer.byteLength(b.body) > 65536) {
      return reply.code(400).send({ error: "invalid team, author or body (maximum 65536 UTF-8 bytes)" });
    }
    const result = await pool.query("INSERT INTO am_board_posts(team, author, body) VALUES ($1,$2,$3) RETURNING *", [b.team, b.author, b.body]);
    return reply.code(201).send(post(result.rows[0]));
  });
  app.get("/v1/board/posts", async (request, reply) => {
    const q = request.query as Record<string, unknown>;
    const limit = q.limit === undefined ? 20 : positive(q.limit, 100);
    const before = q.before === undefined ? undefined : positive(q.before);
    if (!validLabel(q.team) || limit === undefined || (q.before !== undefined && before === undefined)) {
      return reply.code(400).send({ error: "invalid team, limit or before" });
    }
    const result = await pool.query(`SELECT * FROM am_board_posts WHERE team=$1 AND ($2::bigint IS NULL OR id<$2) ORDER BY id DESC LIMIT $3`, [q.team, before ?? null, limit]);
    return result.rows.map(post);
  });
  app.put("/v1/directory/profiles", async (request, reply) => {
    const b = request.body;
    if (!fields(b, ["team", "agent", "display_name", "description"]) || !validLabel(b.team)
      || !validLabel(b.agent) || !validLabel(b.display_name) || b.description.includes("\0") || Buffer.byteLength(b.description) > 4096) {
      return reply.code(400).send({ error: "invalid profile; description maximum 4096 UTF-8 bytes" });
    }
    const result = await pool.query(`INSERT INTO am_agent_profiles(team,agent,display_name,description) VALUES ($1,$2,$3,$4)
      ON CONFLICT(team,agent) DO UPDATE SET display_name=excluded.display_name, description=excluded.description,
      updated_at=to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"') RETURNING *`, [b.team,b.agent,b.display_name,b.description]);
    return result.rows[0];
  });
  app.get("/v1/directory/profiles", async (request, reply) => {
    const q = request.query as Record<string, unknown>;
    if (!validLabel(q.team) || !validLabel(q.agent)) return reply.code(400).send({ error: "invalid team or agent" });
    const result = await pool.query("SELECT * FROM am_agent_profiles WHERE team=$1 AND agent=$2", [q.team,q.agent]);
    return result.rows[0] ?? reply.code(404).send({ error: "profile not found", code: "profile_not_found" });
  });
}
